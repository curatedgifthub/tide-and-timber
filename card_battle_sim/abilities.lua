-- Each non-vanilla card is mapped explicitly; operations are resolved in battle.lua.
-- D=Deploy, P=Effect-play, C=Chain trigger, L=Last Breath, T=Turn start.
local A={handlers={}}
local function op(name,n,target,other)
  local a={op=name,n=n,target=target};if other then for k,v in pairs(other) do a[k]=v end end;return a
end
local function put(f,i,trigger,...)
  A[f]=A[f] or {}
  A[f][i]=A[f][i] or {}
  A[f][i][trigger]={...}
end
local D=function(f,i,...)put(f,i,'deploy',...)end
local P=function(f,i,...)put(f,i,'play',...)end
local C=function(f,i,...)put(f,i,'chain',...)end
local L=function(f,i,...)put(f,i,'death',...)end
local T=function(f,i,...)put(f,i,'turn',...)end
-- shorthand operations; each target represents a set of eligible entities, not a generic substitute.
local draw=function(n,extra)return op('draw',n,nil,extra)end
local buff=function(n,t,extra)return op('buff',n,t,extra)end
local debuff=function(n,t,extra)return op('debuff',n,t,extra)end
local hit=function(n,t,extra)return op('damage',n,t,extra)end
local heal=function(n,t,extra)return op('heal',n,t,extra)end
local guard=function(n,t,extra)return op('guard',n,t,extra)end
local search=function(n,typ,extra)return op('search',n,typ,extra)end
local recover=function(n,typ,extra)return op('recover',n,typ,extra)end
local move=function(kind,t,extra)return op('move',kind,t,extra)end
local special=function(name,extra)return op(name,nil,nil,extra)end
