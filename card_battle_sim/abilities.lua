function A.register_operation(name,fn)
  assert(type(name)=='string' and type(fn)=='function' and not A.handlers[name])
  A.handlers[name]=fn
end
function A.get(card,trigger)
  local a=A[card.faction] and A[card.faction][card.number]
  return a and a[trigger] or nil
end
return A
