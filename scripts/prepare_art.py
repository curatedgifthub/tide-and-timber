"""Build or audit ID-named gameplay thumbnails from the supplied artwork."""
import argparse
import json
from collections import deque
from pathlib import Path
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "scripts/card_art.json"
ART = ROOT / "tabletop/assets"
INDEX = ROOT / "tabletop/card_art.lua"


def index_source(sources):
    """The game's card pool: one entry per card that has its own illustration."""
    def key(card_id):
        faction, number = card_id.split(":")
        return faction, int(number)
    lines = ["-- Generated by scripts/prepare_art.py from scripts/card_art.json. Do not edit.",
             "-- A card is in the game only if it has an entry here.",
             "return {"]
    for card_id in sorted(sources, key=key):
        faction, number = key(card_id)
        lines.append(f'  ["{card_id}"]="tabletop/assets/{faction.lower()}/{number}.png",')
    lines.append("}")
    return "\n".join(lines) + "\n"


# These source files have an opaque background painted in (plain white, or a drawn
# grey/white checkerboard). The thumbnail clears background pixels connected to the
# image border. The source files themselves are never modified.
OPAQUE_BACKGROUND = {"Water:72", "Water:73", "Super:70"}
# Painted on solid black instead. Only pixels connected to the border are cleared.
DARK_BACKGROUND = {"Super:30"}


def clear_background(image, dark=False):
    width, height = image.size
    pixels = image.load()

    def background(xy):
        r, g, b, a = pixels[xy]
        if dark:
            return a > 0 and max(r, g, b) <= 6
        return a > 0 and min(r, g, b) >= 200 and max(r, g, b) - min(r, g, b) <= 8

    seen = bytearray(width * height)
    queue = deque()
    for x in range(width):
        queue.extend([(x, 0), (x, height - 1)])
    for y in range(height):
        queue.extend([(0, y), (width - 1, y)])
    while queue:
        x, y = queue.popleft()
        i = y * width + x
        if seen[i] or not background((x, y)):
            continue
        seen[i] = 1
        pixels[x, y] = (0, 0, 0, 0)
        if x > 0: queue.append((x - 1, y))
        if x < width - 1: queue.append((x + 1, y))
        if y > 0: queue.append((x, y - 1))
        if y < height - 1: queue.append((x, y + 1))
    return image


def thumbnail(source, card_id):
    with Image.open(source) as original:
        image = original.convert("RGBA")
    if card_id in OPAQUE_BACKGROUND:
        image = clear_background(image)
    elif card_id in DARK_BACKGROUND:
        image = clear_background(image, dark=True)
    bounds = image.getchannel("A").point(lambda alpha: 255 if alpha > 42 else 0).getbbox()
    image = image.crop(bounds)
    edge = 512 if card_id in {"Fantasy:48", "Water:43"} else 224
    image.thumbnail((edge, edge), Image.Resampling.LANCZOS)
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = json.loads(SOURCES.read_text())
    if len(set(sources.values())) != len(sources):
        raise ValueError("A source illustration is assigned to more than one card.")
    expected = set()
    for card_id, source in sources.items():
        faction, number = card_id.split(":")
        path = ART / faction.lower() / (str(int(number)) + ".png")
        expected.add(path)
        image = thumbnail(ROOT / source, card_id)
        if args.check:
            with Image.open(path) as saved:
                if saved.size != image.size or any(
                    band.getbbox() for band in ImageChops.difference(image, saved.convert("RGBA")).split()
                ):
                    raise ValueError(f"{card_id} differs from {source}")
        else:
            path.parent.mkdir(exist_ok=True)
            image.save(path, optimize=True)
    index = index_source(sources)
    if args.check:
        if not INDEX.exists() or INDEX.read_text() != index:
            raise ValueError(f"{INDEX} is out of date; run scripts/prepare_art.py")
    else:
        INDEX.write_text(index)
    extra = set(ART.glob("*/*.png")) - expected
    if extra:
        raise ValueError(f"Thumbnails without source mappings: {sorted(extra)}")
    print(f"{len(expected)} unique card IDs and source illustrations verified.")


if __name__ == "__main__":
    main()
